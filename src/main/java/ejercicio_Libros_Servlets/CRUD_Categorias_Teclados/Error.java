package ejercicio_Libros_Servlets.CRUD_Categorias_Teclados;

public class Error {
	private String mensaje;

	public Error() {
		super();
	}

	public Error(String mensaje) {
		super();
		this.mensaje = mensaje;
	}

	public String getMensaje() {
		return mensaje;
	}

	public void setMensaje(String mensaje) {
		this.mensaje = mensaje;
	}

}
